import { awards, experience, flagshipProjects, profile, projects, projectBySlug, type Project } from '../../src/content';
import { formatPeriod } from '../../src/lib/format';

/** Skill icons (skillicons.dev) shown in the Stack row, in reading order. */
const STACK_ICONS = [
  'ts', 'py', 'dart', 'rust', 'cpp', 'nodejs', 'nestjs', 'fastapi', 'flutter', 'nextjs', 'react', 'tailwind',
  'postgres', 'supabase', 'mongodb', 'firebase', 'redis', 'docker', 'gcp', 'aws', 'linux', 'git',
];

const picture = (base: string, alt: string, extra = '') =>
  `<picture><source media="(prefers-color-scheme: dark)" srcset="${base}-dark.svg"><img alt="${alt}" src="${base}-light.svg"${extra}></picture>`;

function projectHref(site: string, p: Project): string | undefined {
  return p.caseStudy ? `${site}/work/${p.slug}` : p.links?.[0]?.href;
}

export function readme(site: string): string {
  const linkRow = [
    `<a href="${site}"><b>${site.replace(/^https?:\/\//, '')}</b></a>`,
    `<a href="mailto:${profile.email}">${profile.email}</a>`,
    ...profile.links.filter((l) => l.label !== 'GitHub').map((l) => `<a href="${l.href}">${l.label}</a>`),
  ].join(' &nbsp;·&nbsp; ');

  const cardPairs: string[] = [];
  for (let i = 0; i < flagshipProjects.length; i += 2) {
    cardPairs.push(
      flagshipProjects
        .slice(i, i + 2)
        .map((p) => `<a href="${projectHref(site, p)}">${picture(`./profile/cards/${p.slug}`, `${p.name}: ${p.tagline}`, ' width="49%"')}</a>`)
        .join('\n'),
    );
  }

  const more = projects
    .filter((p) => p.tier !== 'flagship')
    .map((p) => {
      const href = projectHref(site, p);
      const name = href ? `[**${p.name}**](${href})` : `**${p.name}**`;
      const note = p.award ?? p.metrics?.[0] ? ` <sub>${p.award ?? `${p.metrics![0].value} ${p.metrics![0].label}`}</sub>` : '';
      return `| ${name} | ${p.tagline}${note} | <sub>${p.stack.slice(0, 4).join(' · ')}</sub> |`;
    })
    .join('\n');

  const roles = experience
    .filter((e) => e.kind !== 'campus')
    .map((e) => {
      const built = e.projects.map((s) => projectBySlug(s)!).map((p) => `[${p.name}](${projectHref(site, p)})`);
      return `**${e.role}** · ${e.org}${e.orgNote ? ` <sub>${e.orgNote}</sub>` : ''}  
<sub>${formatPeriod(e.period).toUpperCase()} · ${e.mode.toUpperCase()}</sub>  
${e.summary}${built.length ? ` Built here: ${built.join(', ')}.` : ''}`;
    })
    .join('\n\n');

  const campus = experience
    .filter((e) => e.kind === 'campus')
    .map((e) => `${e.role}, ${e.org} <sub>(${formatPeriod(e.period)})</sub>`)
    .join(' · ');

  const icons = `https://skillicons.dev/icons?i=${STACK_ICONS.join(',')}&perline=11`;

  return `<!-- Generated by \`npm run profile\` from src/content. Edit the content, not this file. -->

<a href="${site}">${picture('./profile/banner', `${profile.name} — ${profile.role}`, ' width="100%"')}</a>

<p align="center">${linkRow}</p>

<br>

${profile.intro}

### Now

- **Building [CrediTouch](${site}/work/creditouch)**: accounts receivable that runs itself. I ran 10+ customer interviews before writing code, then built the whole backend.
- **SDE Intern at COPIOUS**: voice AI live scoring for [Tripple Double](${site}/work/tripple-double), and [CVMorph](${site}/work/cvmorph) for the talent team.
- **${profile.availability.text}**. Remote first, happy to relocate.

### Selected work

${cardPairs.join('\n\n')}

<details>
<summary><b>More projects</b> · ${projects.length - flagshipProjects.length} more, from AI agents to a C++ process manager</summary>
<br>

| Project | What it is | Stack |
|---|---|---|
${more}

</details>

### Experience

${roles}

<sub>ALSO</sub> ${campus}

### Stack

<a href="${site}/#capabilities"><picture><source media="(prefers-color-scheme: dark)" srcset="${icons}&theme=dark"><img alt="TypeScript, Python, Dart, Rust, C++, Node.js, NestJS, FastAPI, Flutter, Next.js, React, Tailwind, PostgreSQL, Supabase, MongoDB, Firebase, Redis, Docker, GCP, AWS, Linux, Git" src="${icons}&theme=light"></picture></a>

### Recognition

${awards.map((a) => `- **${a.title}**, ${a.detail}${a.year ? ` <sub>${a.year}</sub>` : ''}`).join('\n')}

<br>

<p align="center"><sub>This README and <a href="${site}">${site.replace(/^https?:\/\//, '')}</a> are built from the same typed content, in this repository. How it works: <a href="./docs/DEVELOPMENT.md">docs/DEVELOPMENT.md</a></sub></p>
`;
}
